#!/usr/bin/env python3
"""Prebaking steps over a DuckDB database, shared by the benchmarks'
scripts. Runs the `duckdb` CLI (agent mode off), so needs no Python
package. Each step reads and writes files of a benchmark's data directory:

  keys <db> <out>      checks out/keys.json's keys on the data; writes
                       out/primary_keys.json, out/foreign_keys.json (those
                       that hold) and out/dropped_keys.json
  schema <db> <out>    out/schema.sql: CREATE TABLEs with the kept primary keys
  counts <db> <out>    out/cardinalities.json
  parquet <db> <out>   out/parquet/<table>.parquet
  profile <db> <out> <jobs>
                       out/profiles/duckdb/<q>.json for each out/queries/**.sql,
                       several at once, each in a read-only process of one
                       thread; failures in out/profile_failures.json
  version              DuckDB's version
"""

import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path


def duck(db, sql, readonly=False, fmt="-json", timeout=None):
    env = {k: v for k, v in os.environ.items() if k != "AI_AGENT"}
    args = ["duckdb"] + (["-readonly"] if readonly else []) + [fmt, str(db)]
    try:
        r = subprocess.run(args, input=sql, capture_output=True, text=True, env=env, timeout=timeout)
    except subprocess.TimeoutExpired:
        raise RuntimeError(f"timed out after {timeout} s")
    if r.returncode != 0 or r.stderr.strip().startswith("Error"):
        raise RuntimeError(f"{sql[:200]}: {r.stderr.strip()}")
    return r.stdout


def rows(db, sql):
    out = duck(db, sql, readonly=True).strip()
    return json.loads(out) if out else []


def tables(db):
    return [r["table_name"] for r in rows(db, "SELECT table_name FROM information_schema.tables "
                                              "WHERE table_schema = 'main' ORDER BY table_name;")]


def columns(db, table):
    return rows(db, f"SELECT column_name, data_type, is_nullable = 'YES' AS nullable "
                    f"FROM information_schema.columns WHERE table_name = '{table}' "
                    f"ORDER BY ordinal_position;")


def keys(db, out):
    spec = json.loads((out / "keys.json").read_text())
    dropped, primary, foreign = [], {}, []
    for table, cols in spec["primary"].items():
        c = ", ".join(cols)
        nulls = " OR ".join(f"{x} IS NULL" for x in cols)
        [r] = rows(db, f"SELECT count(*) - (SELECT count(*) FROM (SELECT DISTINCT {c} FROM {table})) AS dup, "
                       f"count(*) FILTER (WHERE {nulls}) AS nulls FROM {table};")
        if r["dup"] or r["nulls"]:
            dropped.append({"kind": "primary", "table": table, "columns": cols,
                            "reason": f"{r['dup']} duplicates, {r['nulls']} NULL"})
        else:
            primary[table] = cols
    for fk in spec["foreign"]:
        t, cs, r_, rs = fk["table"], fk["columns"], fk["references"], fk["referenced"]
        nulls = " OR ".join(f"{x} IS NULL" for x in cs)
        on = " AND ".join(f"t.{a} = r.{b}" for a, b in zip(cs, rs))
        [r] = rows(db, f"SELECT (SELECT count(*) FROM {t} WHERE {nulls}) AS nulls, "
                       f"(SELECT count(*) FROM {t} t WHERE NOT ({nulls}) AND NOT EXISTS "
                       f"(SELECT 1 FROM {r_} r WHERE {on})) AS orphans;")
        # A foreign key references a key: the referenced columns must be one.
        referenced_key = primary.get(r_) is not None and sorted(primary[r_]) == sorted(rs)
        if r["nulls"] or r["orphans"] or not referenced_key:
            why = f"{r['nulls']} NULL, {r['orphans']} orphans" + ("" if referenced_key else ", references no kept key")
            dropped.append({"kind": "foreign", **fk, "reason": why})
        else:
            foreign.append(fk)
    (out / "primary_keys.json").write_text(json.dumps(primary, indent=1) + "\n")
    (out / "foreign_keys.json").write_text(json.dumps(foreign, indent=1) + "\n")
    (out / "dropped_keys.json").write_text(json.dumps(dropped, indent=1) + "\n")
    print(f"keys: {len(primary)} primary, {len(foreign)} foreign kept, {len(dropped)} dropped", file=sys.stderr)


def schema(db, out):
    primary = json.loads((out / "primary_keys.json").read_text())
    lines = ["-- Generated by prepare/duck.py from the DuckDB database: its tables, with",
             "-- the primary keys that hold on the data."]
    for t in tables(db):
        cols = [f"  {c['column_name']} {c['data_type']}{'' if c['nullable'] else ' NOT NULL'}" for c in columns(db, t)]
        if t in primary:
            cols.append(f"  PRIMARY KEY ({', '.join(primary[t])})")
        lines.append(f"CREATE TABLE {t} (\n" + ",\n".join(cols) + "\n);")
    (out / "schema.sql").write_text("\n".join(lines) + "\n")


def counts(db, out):
    result = {t: rows(db, f"SELECT count(*) AS n FROM {t};")[0]["n"] for t in tables(db)}
    (out / "cardinalities.json").write_text(json.dumps(result, indent=1, sort_keys=True) + "\n")


def parquet(db, out):
    (out / "parquet").mkdir(exist_ok=True)
    for t in tables(db):
        path = out / "parquet" / f"{t}.parquet"
        if not path.exists():
            duck(db, f"COPY {t} TO '{path}' (FORMAT parquet);", readonly=True)


# Seconds a profile may take; a query slower is no reference plan.
PROFILE_TIMEOUT = int(os.environ.get("PROFILE_TIMEOUT", "1800"))


def profile_one(db, sql_path, json_path):
    sql = sql_path.read_text().strip().rstrip(";")
    script = ("PRAGMA disable_print_progress_bar;\nSET threads = 1;\n"
              f"EXPLAIN (ANALYZE, FORMAT JSON)\n{sql}\n;\n")
    try:
        text = duck(db, script, readonly=True, fmt="-list", timeout=PROFILE_TIMEOUT)
    except RuntimeError as e:
        return str(e)
    start = text.find("\n{") + 1 if not text.startswith("{") else 0
    body = text[start:]
    if not body.startswith("{"):
        return f"no profile in output: {text[:200]}"
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(body)
    return None


def profile(db, out, jobs):
    queries = sorted((out / "queries").rglob("*.sql"))
    names = [q.relative_to(out / "queries").with_suffix("").as_posix() for q in queries]
    dest = [out / "profiles" / "duckdb" / f"{n}.json" for n in names]
    with ThreadPoolExecutor(int(jobs)) as pool:
        errors = list(pool.map(lambda a: profile_one(db, *a), zip(queries, dest)))
    failures = {n: e for n, e in zip(names, errors) if e}
    (out / "profile_failures.json").write_text(json.dumps(failures, indent=1) + "\n")
    print(f"profiles: {len(names) - len(failures)} of {len(names)}", file=sys.stderr)


def version():
    [r] = json.loads(duck(":memory:", "SELECT library_version AS v, source_id AS s FROM pragma_version();"))
    print(f"{r['v']} ({r['s']})")


if __name__ == "__main__":
    step, *args = sys.argv[1:]
    if step == "version":
        version()
    else:
        db, out, *rest = args
        {"keys": keys, "schema": schema, "counts": counts, "parquet": parquet, "profile": profile}[step](
            Path(db), Path(out), *rest)
